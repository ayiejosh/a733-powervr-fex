#include <fcntl.h>
#include <stdio.h>
#include <stdint.h>
#include <sys/mman.h>
#include <unistd.h>
static const int offs[] = {
   0x130,0x160,0x164,0x1a8,0x1f0,0x200,0x270,0x2c0,0x2f8,0x300,0x310,0x318,0x3a0,
   0x400,0x404,0x408,0x40c,0x410,0x414,0x418,0x41c,0x420,0x430,0x468,0x4a4,0x500,0x508,
   0x520,0x528,0x530,0x5c00,0x6000,0x6020,
   0xb00,0xb30,0xb38,0xb40,0xb48,0xb50,0xb58,0xb60,0xb68,0xb70,0xb78,0xb80,0xb88,
   0xb98,0xba0,0xba8,0xbb0,0xbc8,0xbd8,
   0xc00,0xc08,0xc10,0xc18,0xc20,0xc28,0xc38,0xc40,0xc68,0xc80,0xc88,0xc90,0xc98,
   0xce0,0xcf0,0xd20,
};
int main(int argc, char **argv) {
   volatile uint8_t *base;
   int fd = open("/dev/mem", O_RDONLY | O_SYNC);
   unsigned i;
   if (fd < 0) { perror("open"); return 1; }
   base = mmap(NULL, 0x10000, PROT_READ, MAP_SHARED, fd, 0x1800000ULL);
   if (base == MAP_FAILED) { perror("mmap"); return 1; }
   printf("--- %s ---\n", argc > 1 ? argv[1] : "dump");
   for (i = 0; i < sizeof(offs)/sizeof(offs[0]); i++) {
      uint32_t v = *(volatile uint32_t *)(base + offs[i]);
      if (v) printf("%04x=%08x ", offs[i], v);
   }
   printf("\n");
   munmap((void *)base, 0x10000); close(fd); return 0;
}
